import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('Рабочее пространство: подборка, живой расчёт, согласование, заявка, потребности и аналитика',async()=>{
 const html=await fs.readFile(new URL('../dist/index.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://optima.example/#offers',pretendToBeVisual:true});
 for(const key of ['window','document','location','history','localStorage','FormData','HTMLElement'])globalThis[key]=dom.window[key];
 window.scrollTo=()=>{};
 window.matchMedia=()=>({matches:false});
 await import('../dist/js/app.js');
 const click=selector=>{const e=document.querySelector(selector);assert.ok(e,'Missing '+selector);e.click();};
 const input=(selector,value)=>{const e=document.querySelector(selector);assert.ok(e,selector);e.value=value;e.dispatchEvent(new window.Event('input',{bubbles:true}));};
 const change=(selector,value)=>{const e=document.querySelector(selector);e.value=value;e.dispatchEvent(new window.Event('change',{bubbles:true}));};
 const digits=selector=>document.querySelector(selector).textContent.replace(/\D/g,'');
 const shell=document.querySelector('.shell'),rail=document.querySelector('.side-nav');
 const assertSection=id=>{
  assert.equal(document.querySelector('.side-nav [aria-current="page"]').dataset.view,id);
  assert.equal(document.querySelectorAll('.side-nav .active').length,1);
  assert.equal(document.querySelector('.tabs [aria-current="page"]').dataset.view,id);
  assert.equal(location.hash,'#'+id);
  assert.equal(document.querySelector('.shell'),shell,'Не пересоздавать оболочку при переходах');
  assert.equal(document.querySelector('.side-nav'),rail,'Сохранять навигацию и её положение');
 };
 assert.equal(document.querySelector('[data-action="bank"]'),null);
 assert.deepEqual([...document.querySelectorAll('.side-nav [data-view]')].map(e=>e.dataset.view),['offers','orders','needs','analytics']);
 assertSection('offers');
 assert.equal(document.querySelectorAll('.offer-card').length,6);
 click('[data-action="scope"][data-scope="matched"]');assert.equal(document.querySelectorAll('.offer-card').length,3);
 change('#category','Упаковка');assert.equal(document.querySelectorAll('.offer-card').length,1);
 click('[data-action="scope"][data-scope="all"]');assert.equal(document.querySelectorAll('.offer-card').length,3);
 change('#category','Все');
 input('#offer-search','перчатки');assert.equal(document.querySelectorAll('.offer-card').length,1);assert.equal(document.querySelector('#offers-count').textContent,'1');
 assert.equal(document.querySelector('#purchase-preview').dataset.offerId,'gloves');
 input('#offer-search','несуществующий товар');assert.match(document.querySelector('#offers-grid').textContent,/пока нет/);assert.equal(document.querySelector('#quote-quantity'),null);
 input('#offer-search','');
 click('[data-action="select-offer"][data-id="bags"]');
 assert.equal(document.querySelector('#quote-quantity').value,'1000');assert.equal(digits('#quote-total'),'3050');
 const quoteInput=document.querySelector('#quote-quantity');
 input('#quote-quantity','2000');assert.equal(digits('#quote-total'),'5850');
 click('[data-action="favorite"][data-id="bags"]');
 assert.equal(document.querySelector('#quote-quantity'),quoteInput,'Не терять форму и объём при обновлении избранного');
 assert.equal(document.querySelector('#quote-quantity').value,'2000');
 input('#quote-quantity','');assert.equal(document.querySelector('[data-action="quote-open"]').disabled,true);
 click('[data-action="quote-plus"]');assert.equal(document.querySelector('[data-action="quote-open"]').disabled,false);
 input('#quote-quantity','2000');
 click('[data-action="quote-open"]');assert.equal(document.querySelector('#app').inert,true);assert.equal(document.querySelector('#quantity').value,'2000');
 const drawer=document.querySelector('.drawer');
 click('[data-action="detail-tab"][data-tab="group"]');assert.equal(document.querySelector('.drawer'),drawer,'Не выдвигать панель повторно при смене её вкладки');
 click('[data-action="detail-tab"][data-tab="terms"]');assert.equal(document.querySelector('.drawer'),drawer);
 assert.equal(document.querySelector('[data-action="review"]').disabled,true);
 click('#consent');assert.equal(document.querySelector('[data-action="review"]').disabled,false);
 input('#quantity','');assert.equal(document.querySelector('[data-action="review"]').disabled,true);
 click('[data-action="quantity-up"]');assert.equal(document.querySelector('[data-action="review"]').disabled,false);
 input('#quantity','2000');click('[data-action="review"]');assert.match(document.querySelector('#overlay-root').textContent,/Подтверждение участия/);
 click('[data-action="confirm"]');assert.match(document.querySelector('#overlay-root').textContent,/Вы в закупке/);
 assert.equal(document.querySelector('#quote-quantity').value,'2000');assert.equal(document.querySelector('#quote-quantity').disabled,true);
 assert.equal(digits('#quote-total'),'5850');
 click('[data-action="success-orders"]');assert.equal(document.querySelector('#app').inert,false);assertSection('orders');assert.equal(document.querySelectorAll('.order-card').length,1);
 const stored=JSON.parse(localStorage.getItem('optima-vtb-state-v1'));assert.equal(stored.orders.length,1);assert.equal(stored.orders[0].quantity,2000);assert.equal(stored.orders[0].calculation.groupTotal,5850);
 click('[data-action="order-detail"]');click('[data-action="cancel-ask"]');click('[data-action="cancel-confirm"]');
 assert.equal(JSON.parse(localStorage.getItem('optima-vtb-state-v1')).orders[0].status,'cancelled');
 document.querySelector('.side-nav [data-view="needs"]').focus();click('.side-nav [data-view="needs"]');assertSection('needs');assert.equal(document.activeElement.dataset.view,'needs');click('[data-action="new-need"]');change('#need-product','bags');change('#need-price','2');
 document.querySelector('#need-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
 assert.equal(JSON.parse(localStorage.getItem('optima-vtb-state-v1')).needs.length,4);
 const links=[...document.querySelectorAll('[data-action="offer"][data-price="2"]')];assert.equal(links.length,1);links[0].click();
 click('#consent');assert.equal(document.querySelector('[data-action="review"]').disabled,true,'Не допускать невыгодную закупку');
 click('[data-action="close"]');
 click('.side-nav [data-view="analytics"]');assertSection('analytics');assert.equal(document.querySelectorAll('.chart-column').length,6);
 assert.match(document.querySelector('.economy-main').textContent,/8[\s\u00a0\u202f]*610/);
 document.dispatchEvent(new window.KeyboardEvent('keydown',{key:'/',bubbles:true}));
 assertSection('offers');assert.equal(document.activeElement.id,'offer-search');
 click('[data-action="scope"][data-scope="favorites"]');assert.equal(document.querySelectorAll('.offer-card').length,1);
 click('[data-action="favorite"][data-id="bags"]');assert.equal(document.querySelectorAll('.offer-card').length,0);assert.equal(document.querySelector('#quote-quantity'),null);
 click('[data-action="clear-filter"]');
 window.matchMedia=query=>({matches:query.includes('max-width:1179px')});
 click('[data-action="select-offer"][data-id="bags"]');assert.ok(document.querySelector('.drawer'),'На небольшом экране строка открывает условия');
 click('[data-action="close"]');
 dom.window.close();
});
